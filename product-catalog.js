/**
 * Ключ сравнения названий: регистр, лишние пробелы и разница «ё/е» не важны.
 * По нему приложение понимает, что продукт уже есть в справочнике.
 * @param {string} name
 */
export function productKey(name) {
  return String(name || '')
    .trim()
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/\s+/g, ' ');
}

